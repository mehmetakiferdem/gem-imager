# Remove the WinUSB driver wdi-simple installed for the board's DFU interface.
#
# Each wdi-simple run adds another copy of the driver package to the driver
# store, and the self-signed certificate it was signed with stays trusted, so
# both are removed: by the installer before it runs wdi-simple again, and by
# the uninstaller.

$deviceId = "VID_0451&PID_6165"

Get-ChildItem "$env:windir\INF\oem*.inf" -ErrorAction SilentlyContinue | ForEach-Object {
    $inf = Get-Content $_.FullName -Raw -ErrorAction SilentlyContinue
    if ($inf -match 'Provider\s*=\s*"libwdi"' -and $inf.Contains($deviceId)) {
        Write-Output "Removing driver package $($_.Name)"
        pnputil /delete-driver $_.Name /uninstall /force | Out-Null
    }
}

foreach ($store in "Root", "TrustedPublisher") {
    Get-ChildItem "Cert:\LocalMachine\$store" -ErrorAction SilentlyContinue |
        Where-Object Subject -eq "CN=USB\$deviceId (libwdi autogenerated)" |
        ForEach-Object {
            Write-Output "Removing certificate $($_.Thumbprint) from $store"
            Remove-Item $_.PSPath
        }
}
